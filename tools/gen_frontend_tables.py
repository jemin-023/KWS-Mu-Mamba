#!/usr/bin/env python3
"""
Generate fixed-point C tables for mm_frontend.c:
1. Hann window (512 points, Q15)
2. Bit reversal table (512 points)
3. Twiddle factors for 512-point FFT (256 pairs, Q15)
4. 40 sparse triangular Mel filterbank weights (Q15)
"""

import math
import sys
from pathlib import Path

def hz_to_mel(f):
    return 2595.0 * math.log10(1.0 + f / 700.0)

def mel_to_hz(m):
    return 700.0 * (10.0 ** (m / 2595.0) - 1.0)

def generate_header(out_path: Path):
    fft_size = 512
    sr = 16000
    n_mels = 40
    f_min = 20.0
    f_max = 8000.0

    lines = []
    lines.append("/* Auto-generated by tools/gen_frontend_tables.py - DO NOT EDIT */")
    lines.append("#ifndef MM_FRONTEND_TABLES_H")
    lines.append("#define MM_FRONTEND_TABLES_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")

    # 1. Hann Window (Q15)
    # w[n] = 0.5 * (1 - cos(2*pi*n / N))
    lines.append(f"/* 512-point Hann window in Q15 (0..32767) */")
    lines.append(f"static const int16_t mm_hann_window_q15[{fft_size}] = {{")
    hann_vals = []
    for n in range(fft_size):
        w = 0.5 * (1.0 - math.cos(2.0 * math.pi * n / fft_size))
        val = int(round(w * 32767.0))
        val = max(0, min(32767, val))
        hann_vals.append(str(val))
    for i in range(0, fft_size, 8):
        lines.append("    " + ", ".join(hann_vals[i:i+8]) + ",")
    lines.append("};\n")

    # 2. Bit reversal table for 512 points (9 bits)
    lines.append(f"/* 512-point bit-reversal permutation */")
    lines.append(f"static const uint16_t mm_bitrev_512[{fft_size}] = {{")
    bitrev_vals = []
    for i in range(fft_size):
        rev = 0
        tmp = i
        for _ in range(9):
            rev = (rev << 1) | (tmp & 1)
            tmp >>= 1
        bitrev_vals.append(str(rev))
    for i in range(0, fft_size, 8):
        lines.append("    " + ", ".join(bitrev_vals[i:i+8]) + ",")
    lines.append("};\n")

    # 3. Twiddle factors W_512^k = cos(2*pi*k/512) - j*sin(2*pi*k/512)
    # k in [0..255]
    lines.append("/* 256 twiddle factors in Q15: cos(2*pi*k/512) and -sin(2*pi*k/512) */")
    lines.append("static const int16_t mm_twiddle_re_q15[256] = {")
    cos_vals = []
    sin_vals = []
    for k in range(256):
        c = math.cos(2.0 * math.pi * k / fft_size)
        s = math.sin(2.0 * math.pi * k / fft_size)
        val_c = max(-32768, min(32767, int(round(c * 32767.0))))
        # Note: -sin in W = e^{-j*2pi*k/N}
        val_s = max(-32768, min(32767, int(round(-s * 32767.0))))
        cos_vals.append(str(val_c))
        sin_vals.append(str(val_s))
    for i in range(0, 256, 8):
        lines.append("    " + ", ".join(cos_vals[i:i+8]) + ",")
    lines.append("};\n")

    lines.append("static const int16_t mm_twiddle_im_q15[256] = {")
    for i in range(0, 256, 8):
        lines.append("    " + ", ".join(sin_vals[i:i+8]) + ",")
    lines.append("};\n")

    # 4. Sparse Mel filterbank
    mel_min = hz_to_mel(f_min)
    mel_max = hz_to_mel(f_max)
    mel_points = [mel_min + i * (mel_max - mel_min) / (n_mels + 1) for i in range(n_mels + 2)]
    hz_points = [mel_to_hz(m) for m in mel_points]
    bin_points = [(f * fft_size / sr) for f in hz_points]

    lines.append("/* Sparse Mel Filterbank Definition: 40 filters */")
    lines.append("typedef struct {")
    lines.append("    uint16_t start_bin;")
    lines.append("    uint16_t num_bins;")
    lines.append("    uint16_t weight_offset;")
    lines.append("} mm_mel_filter_info_t;\n")

    all_weights = []
    filter_infos = []

    for m in range(n_mels):
        left_bin = int(math.floor(bin_points[m]))
        center_bin = bin_points[m + 1]
        right_bin = int(math.ceil(bin_points[m + 2]))

        # Ensure bins within [0, fft_size // 2]
        left_bin = max(0, min(fft_size // 2, left_bin))
        right_bin = max(left_bin + 1, min(fft_size // 2, right_bin))

        f_weights = []
        for k in range(left_bin, right_bin + 1):
            if k < center_bin:
                w = (k - bin_points[m]) / (center_bin - bin_points[m]) if (center_bin > bin_points[m]) else 0.0
            elif k == center_bin:
                w = 1.0
            else:
                w = (bin_points[m + 2] - k) / (bin_points[m + 2] - center_bin) if (bin_points[m + 2] > center_bin) else 0.0
            w = max(0.0, min(1.0, w))
            w_q15 = int(round(w * 32767.0))
            f_weights.append(w_q15)

        weight_offset = len(all_weights)
        filter_infos.append((left_bin, len(f_weights), weight_offset))
        all_weights.extend(f_weights)

    lines.append(f"static const mm_mel_filter_info_t mm_mel_filters[{n_mels}] = {{")
    for m, (start, num, offset) in enumerate(filter_infos):
        lines.append(f"    {{ {start}, {num}, {offset} }}, /* mel {m} */")
    lines.append("};\n")

    lines.append(f"static const uint16_t mm_mel_weights_q15[{len(all_weights)}] = {{")
    for i in range(0, len(all_weights), 8):
        lines.append("    " + ", ".join(str(w) for w in all_weights[i:i+8]) + ",")
    lines.append("};\n")

    lines.append("#endif /* MM_FRONTEND_TABLES_H */\n")

    out_path.write_text("\n".join(lines))
    print(f"Generated {out_path} ({len(all_weights)} total sparse mel weights)")

if __name__ == "__main__":
    out_dir = Path("engine/include")
    out_dir.mkdir(parents=True, exist_ok=True)
    generate_header(out_dir / "mm_frontend_tables.h")
